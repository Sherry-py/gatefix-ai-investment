def backers_of(target_name):
    """反向资本穿透：返回持有某标的的机构列表（谁在投）。"""
    return [b for b in BACKER_GRAPH if target_name in b["portfolio"]]


def backers_by_type(backer_type):
    """按机构类型过滤。backer_type ∈ 财务VC/产业资本/国资、政府基金。"""
    return [b for b in BACKER_GRAPH if b["type"] == backer_type]
